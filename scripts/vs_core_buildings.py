"""Compile the reviewed VS-001 extract into exact Rust constants (offline).

Run `python3 scripts/vs_core_buildings.py build` or `check` at the repo root.
No raw upstream parsing, projection, simplification, or runtime dependency.
"""
import hashlib
import json
from decimal import Decimal
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data/vertical-slice/bay-ridge-block-6049/buildings.geojson"
OUTPUT = ROOT / "core/crates/ws-world/src/block_6049.rs"


def scaled(value, scale):
    value = Decimal(value) * scale
    if not value.is_finite() or value != value.to_integral_value():
        raise ValueError("source value does not fit exact fixed-point representation")
    return int(value)


def point(pair):
    lon, lat = pair
    lon, lat = scaled(lon, 10**12), scaled(lat, 10**12)
    if not -180 * 10**12 <= lon <= 180 * 10**12 or not -90 * 10**12 <= lat <= 90 * 10**12:
        raise ValueError("coordinate outside WGS84 range")
    return f"GeoPoint {{ lon_pdeg: {lon}, lat_pdeg: {lat} }}"


def build(source=None):
    raw = SOURCE.read_bytes() if source is None else source
    features = json.loads(raw, parse_float=Decimal)["features"]
    digest = hashlib.sha256(raw).hexdigest()
    lines = [
        "// Generated by scripts/vs_core_buildings.py; do not edit by hand.",
        "// Source: data/vertical-slice/bay-ridge-block-6049/buildings.geojson",
        "use super::{Footprint, GeoPoint, Polygon, Ring, SourceBuilding};",
        "/// SHA-256 of the exact reviewed GeoJSON bytes.",
        f'pub const EXTRACT_SHA256: &str = "{digest}";',
        "/// First 64 bits of the extract SHA-256, interpreted big-endian.",
        f"pub const DATASET_VERSION: u64 = 0x{digest[:16]};",
        "/// All 58 source footprints, in ascending BIN order.",
        "#[rustfmt::skip]",
        "pub static BLOCK_BUILDINGS: &[SourceBuilding] = &[",
    ]
    seen = set()
    for feature in sorted(features, key=lambda f: int(f["properties"]["bin"])):
        prop, geom = feature["properties"], feature["geometry"]
        bin_id = int(prop["bin"])
        if bin_id in seen:
            raise ValueError("duplicate BIN")
        seen.add(bin_id)
        if geom["type"] != "MultiPolygon" or not geom["coordinates"]:
            raise ValueError("expected nonempty MultiPolygon")
        polygons = []
        for polygon in geom["coordinates"]:
            if not polygon:
                raise ValueError("empty polygon")
            rings = []
            for ring in polygon:
                if len(ring) < 4 or ring[0] != ring[-1]:
                    raise ValueError("expected closed ring with at least three vertices")
                rings.append("Ring { points: &[" + ", ".join(point(c) for c in ring) + "] }")
            polygons.append("Polygon { rings: &[" + ", ".join(rings) + "] }")
        height = scaled(prop["height_roof_m"], 1000)
        if height <= 0:
            raise ValueError("height must be positive")
        role = "None" if prop["featured"] is None else f'Some({json.dumps(prop["featured"])})'
        lines += [
            "    SourceBuilding {",
            f"        bin: {bin_id}, bbl: {int(prop['bbl'])}, lot: {prop['lot']},",
            f"        address: {json.dumps(prop['address'])}, building_class: {json.dumps(prop['bldgclass'])},",
            f"        feature_code: {int(prop['feature_code'])}, featured: {role},",
            f"        height_mm: {height}, ground_navd88_mm: {scaled(prop['ground_elevation_m_navd88'], 1000)},",
            f"        floors_milli: {scaled(prop['numfloors'], 1000)}, residential_units: {prop['unitsres']},",
            f"        centroid: {point([prop['centroid_lon'], prop['centroid_lat']])},",
            "        footprint: Footprint { polygons: &[" + ", ".join(polygons) + "] },",
            "    },",
        ]
    return "\n".join(lines + ["];", ""])


if __name__ == "__main__":
    mode = sys.argv[1] if len(sys.argv) == 2 else ""
    if mode == "build":
        OUTPUT.write_text(build(), encoding="utf-8")
    elif mode == "check":
        if OUTPUT.read_text(encoding="utf-8") != build():
            sys.exit("core building constants are stale; regenerate and review dataset/golden changes")
        print("core building constants match VS-001 extract")
    else:
        sys.exit("usage: vs_core_buildings.py build|check")
